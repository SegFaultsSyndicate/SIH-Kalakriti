// web/scripts/gen-verification-css.mjs
//
// The public provenance page (/v/<code>) is rendered by the Go BFF, not by
// SvelteKit, and its stylesheet is inlined in a <style> tag so a stranger
// scanning a tag on a bad connection gets the whole page in one request.
//
// Before this script, that stylesheet was a hand-maintained Go string with
// the palette's hex values copied into it. Nothing checked the copy, so the
// two would drift the first time a token moved. Now the Go file is generated:
// palette.css supplies the values, packages/patterns/verify-page.css supplies
// the rules, and the dark theme -- which the standalone page selects by
// prefers-color-scheme, having no data-theme attribute to read -- is emitted
// from the same [data-theme="dark"] block the apps use.
//
// Usage: node scripts/gen-verification-css.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const out = resolve(root, '../services/bff/internal/bff/handler/verification_css.go');
const CHECK = process.argv.includes('--check');

const palette = readFileSync(resolve(root, 'packages/tokens/src/palette.css'), 'utf8');
const page = readFileSync(resolve(root, 'packages/patterns/verify-page.css'), 'utf8');

/** The declarations of every rule block whose selector list contains `selector`. */
function block(selector) {
  const pattern = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  const parts = [];
  while ((m = pattern.exec(palette)) !== null) {
    if (m[1].includes(selector)) parts.push(m[2]);
  }
  if (parts.length === 0) throw new Error(`palette.css has no block for ${selector}`);
  return parts.join('\n');
}

/** Strip comments and collapse whitespace. The page is served over 2G. */
function squash(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s*([{};:,])\s*/g, '$1')
    .replace(/\s+/g, ' ')
    .replace(/;\}/g, '}')
    .trim();
}

/** `--name` -> value, from a squashed declaration list. */
function declarations(squashed) {
  const map = new Map();
  for (const decl of squashed.split(';')) {
    const colon = decl.indexOf(':');
    const name = decl.slice(0, colon).trim();
    if (colon > 0 && name.startsWith('--')) map.set(name, decl.slice(colon + 1).trim());
  }
  return map;
}

/** Every `--token` named inside a `var(...)` in `text`. */
function varRefs(text) {
  return text
    .split('var(')
    .slice(1)
    .map((tail) => tail.split(')')[0].split(',')[0].trim())
    .filter((name) => name.startsWith('--'));
}

/**
 * Only the tokens this page actually reaches, transitively. Shipping the whole
 * palette would put several KB of unused custom properties in front of someone
 * on a 2G link -- the page's whole point is that it arrives in one small
 * request.
 */
function used(pageCss, ...scopes) {
  const wanted = new Set();
  const queue = varRefs(pageCss);
  while (queue.length > 0) {
    const name = queue.pop();
    if (wanted.has(name)) continue;
    wanted.add(name);
    for (const scope of scopes) {
      const value = scope.get(name);
      if (value !== undefined) queue.push(...varRefs(value));
    }
  }
  return wanted;
}

/** `name:value` for the wanted tokens a scope defines, in palette order. */
function emit(scope, wanted) {
  return [...scope]
    .filter(([name]) => wanted.has(name))
    .map(([name, value]) => `${name}:${value}`)
    .join(';');
}

// :root carries the raw scale; the light aliases sit in the same block list.
const lightScope = declarations(squash(block(':root')));
const darkScope = declarations(squash(block('[data-theme="dark"]')));
const wanted = used(page, lightScope, darkScope);

const css = [
  `:root{color-scheme:light;${emit(lightScope, wanted)}}`,
  squash(page),
  `@media (prefers-color-scheme:dark){:root{color-scheme:dark;${emit(darkScope, wanted)}}}`,
].join('\n');

if (css.includes('`')) throw new Error('CSS contains a backtick and cannot go in a Go raw string');

const go = `// Code generated by web/scripts/gen-verification-css.mjs. DO NOT EDIT.
//
// Source: web/packages/patterns/verify-page.css + web/packages/tokens/src/palette.css.
// Regenerate with \`node web/scripts/gen-verification-css.mjs\` after changing
// either. \`--check\` fails when this file is stale; validate-all.mjs runs it.

package handler

// verificationPageCSS is inlined into the public provenance page. Inlined
// rather than linked so the page renders in a single request with no webfont
// and no second round trip -- see verify-page.css's header for why.
const verificationPageCSS = \`${css}\`
`;

if (CHECK) {
  if (readFileSync(out, 'utf8') !== go) {
    console.error('verification_css.go is stale. Run: node web/scripts/gen-verification-css.mjs');
    process.exit(1);
  }
  console.log('verification CSS: generated file matches palette.css + verify-page.css');
} else {
  writeFileSync(out, go);
  console.log(`verification CSS: wrote ${(css.length / 1024).toFixed(1)} KB to verification_css.go`);
}
