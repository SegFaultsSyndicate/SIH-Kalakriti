// apps/admin/src/lib/csv.ts
//
// Dependency-free CSV: no library anywhere in the monorepo, and this is a
// handful of lines either way. RFC 4180 quoting only (fields containing a
// comma, quote or newline get wrapped and quotes doubled) -- enough for the
// artisan/district/craft data this touches.

export function toCsvField(value: unknown): string {
  const s = value === null || value === undefined ? '' : String(value);
  if (/[",\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

export function toCsv(headers: string[], rows: unknown[][]): string {
  const lines = [headers.map(toCsvField).join(',')];
  for (const row of rows) lines.push(row.map(toCsvField).join(','));
  return lines.join('\r\n');
}

/** Triggers a browser download of the given CSV text. No dependency: Blob + an anchor click. */
export function downloadCsv(filename: string, csv: string): void {
  const blob = new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Parses a CSV file's text into rows of string cells. Handles quoted fields
 * (with embedded commas/newlines/escaped quotes) -- the shape a bulk
 * artisan-onboarding sheet exported from a spreadsheet actually needs, not
 * just a naive split(',').
 */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;
  let i = 0;
  const n = text.length;

  while (i < n) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i++;
        continue;
      }
      field += c;
      i++;
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      i++;
      continue;
    }
    if (c === ',') {
      row.push(field);
      field = '';
      i++;
      continue;
    }
    if (c === '\r') {
      i++;
      continue;
    }
    if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
      i++;
      continue;
    }
    field += c;
    i++;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => !(r.length === 1 && r[0] === ''));
}
